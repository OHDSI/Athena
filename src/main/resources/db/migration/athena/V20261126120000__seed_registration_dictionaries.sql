-- Seed the registration lookups with the existing Arachne IDs and ISO codes.
CREATE TABLE countries (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    alfa2 VARCHAR(255) NOT NULL UNIQUE,
    alfa3 VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE states_provinces (
    id BIGSERIAL PRIMARY KEY,
    country_id BIGINT NOT NULL REFERENCES countries (id) ON UPDATE CASCADE ON DELETE CASCADE,
    name VARCHAR(50) NOT NULL,
    iso_code VARCHAR(10) NOT NULL,
    UNIQUE (country_id, name),
    UNIQUE (country_id, iso_code)
);

CREATE TABLE professional_types (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

